Status ValidateWssClientConfig(const WssClientConfig& config) {
  if (config.server_ip.empty()) {
    return Status::Error(StatusCode::kInvalidArgument,
                         "WSS server IP must not be empty");
  }
  if (config.server_port == 0U) {
    return Status::Error(StatusCode::kInvalidArgument,
                         "WSS server port must be non-zero");
  }
  const bool has_ca = !config.ca_certificate_path.empty();
  const bool has_pin = !config.spki_sha256_base64.empty();
  if (has_ca == has_pin) {
    return Status::Error(
        StatusCode::kInvalidArgument,
        "configure exactly one of CA certificate or SPKI SHA-256 pin");
  }
  if (has_ca && config.server_name.empty()) {
    return Status::Error(StatusCode::kInvalidArgument,
                         "CA verification requires a TLS server name");
  }
  if (!config.server_name.empty() && !IsSafeServerName(config.server_name)) {
    return Status::Error(
        StatusCode::kInvalidArgument,
        "TLS server name must use a bounded safe ASCII host character set");
  }
  if (has_pin) {
    std::array<std::uint8_t, kSha256Bytes> pin{};
    const auto pin_status = DecodeSha256Pin(config.spki_sha256_base64, &pin);
    if (!pin_status.ok()) {
      return pin_status;
    }
  }
  if (config.connect_timeout_ms == 0U ||
      config.connect_timeout_ms > 60000U || config.write_timeout_ms == 0U ||
      config.write_timeout_ms > 60000U) {
    return Status::Error(StatusCode::kInvalidArgument,
                         "WSS connect/write timeouts must be between 1 and 60000 ms");
  }
  if (config.receive_idle_timeout_ms == 0U ||
      config.receive_idle_timeout_ms > 120000U) {
    return Status::Error(
        StatusCode::kInvalidArgument,
        "WSS receive idle timeout must be between 1 and 120000 ms");
  }
  return Status::Ok();
}

