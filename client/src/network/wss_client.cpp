Status WssClient::Impl::Connect() {
  if (connected_ || socket_ != kInvalidSocket || tls_context_ != nullptr ||
      tls_ != nullptr) {
    return Status::Error(StatusCode::kFailedPrecondition,
                         "WSS client is already connected");
  }
  stop_requested_.store(false, std::memory_order_release);
  const auto config_status = ValidateWssClientConfig(config_);
  if (!config_status.ok()) {
    return config_status;
  }
  const auto socket_status = InitializeSocketApi();
  if (!socket_status.ok()) {
    return socket_status;
  }
  if (!config_.spki_sha256_base64.empty()) {
    const auto pin_status =
        DecodeSha256Pin(config_.spki_sha256_base64, &pin_.digest);
    if (!pin_status.ok()) {
      return pin_status;
    }
  }
  const auto deadline = std::chrono::steady_clock::now() +
                        std::chrono::milliseconds(config_.connect_timeout_ms);
  auto status = ConnectTcp(deadline);
  if (status.ok()) {
    status = ConfigureTls();
  }
  if (status.ok()) {
    status = ConnectTls(deadline);
  }
  if (status.ok()) {
    status = UpgradeWebSocket(deadline);
  }
  if (status.ok() &&
      stop_requested_.load(std::memory_order_acquire)) {
    status = CancelledStatus();
  }
  if (!status.ok()) {
    Reset();
    return status;
  }
  connected_ = true;
  return Status::Ok();
}

Status WssClient::Impl::ConnectTcp(const Deadline deadline) {
  if (stop_requested_.load(std::memory_order_acquire)) {
    return CancelledStatus();
  }
  sockaddr_storage address{};
  socklen_t address_size = 0;
  int family = AF_UNSPEC;
  auto* const ipv4 = reinterpret_cast<sockaddr_in*>(&address);
  if (inet_pton(AF_INET, config_.server_ip.c_str(), &ipv4->sin_addr) == 1) {
    family = AF_INET;
    ipv4->sin_family = AF_INET;
    ipv4->sin_port = htons(config_.server_port);
    address_size = sizeof(*ipv4);
  } else {
    auto* const ipv6 = reinterpret_cast<sockaddr_in6*>(&address);
    if (inet_pton(AF_INET6, config_.server_ip.c_str(), &ipv6->sin6_addr) != 1) {
      return Status::Error(StatusCode::kInvalidArgument,
                           "server_ip must be a numeric IPv4 or IPv6 address");
    }
    family = AF_INET6;
    ipv6->sin6_family = AF_INET6;
    ipv6->sin6_port = htons(config_.server_port);
    address_size = sizeof(*ipv6);
  }

  const NativeSocket created_socket = socket(family, SOCK_STREAM, IPPROTO_TCP);
  if (created_socket == kInvalidSocket) {
    return Status::Error(StatusCode::kInternal,
                         "create TCP socket failed");
  }
  {
    std::lock_guard<std::mutex> lock(socket_lifetime_mutex_);
    if (stop_requested_.load(std::memory_order_acquire)) {
      CloseSocket(created_socket);
      return CancelledStatus();
    }
    socket_ = created_socket;
  }
  const auto mode_status = SetNonBlocking(socket_);
  if (!mode_status.ok()) {
    if (stop_requested_.load(std::memory_order_acquire)) {
      return CancelledStatus();
    }
    return mode_status;
  }
  const int result = connect(socket_, reinterpret_cast<const sockaddr*>(&address),
                             address_size);
  if (result == 0) {
    if (stop_requested_.load(std::memory_order_acquire)) {
      return CancelledStatus();
    }
    return Status::Ok();
  }
  if (!ConnectIsInProgress()) {
    if (stop_requested_.load(std::memory_order_acquire)) {
      return CancelledStatus();
    }
    return Status::Error(StatusCode::kInternal,
                         "connect TCP socket failed");
  }
  const auto wait_status =
      WaitForSocket(socket_, false, deadline, stop_requested_);
  if (!wait_status.ok()) {
    return wait_status;
  }
  if (stop_requested_.load(std::memory_order_acquire)) {
    return CancelledStatus();
  }
  int socket_error = 0;
#if defined(_WIN32)
  int error_size = sizeof(socket_error);
#else
  socklen_t error_size = sizeof(socket_error);
#endif
  if (getsockopt(socket_, SOL_SOCKET, SO_ERROR,
                 reinterpret_cast<char*>(&socket_error), &error_size) != 0 ||
      socket_error != 0) {
    if (stop_requested_.load(std::memory_order_acquire)) {
      return CancelledStatus();
    }
    return Status::Error(StatusCode::kInternal,
                         "complete TCP connection failed");
  }
  if (stop_requested_.load(std::memory_order_acquire)) {
    return CancelledStatus();
  }
  return Status::Ok();
}

Status WssClient::Impl::ConfigureTls() {
  tls_context_ = SSL_CTX_new(TLS_client_method());
  if (tls_context_ == nullptr) {
    return OpenSslError("create TLS client context failed");
  }
  if (SSL_CTX_set_min_proto_version(tls_context_, TLS1_2_VERSION) != 1) {
    return OpenSslError("require TLS 1.2 failed");
  }
  SSL_CTX_set_options(tls_context_, SSL_OP_NO_COMPRESSION);
  SSL_CTX_set_verify(tls_context_, SSL_VERIFY_PEER, nullptr);
  if (!config_.spki_sha256_base64.empty()) {
    SSL_CTX_set_cert_verify_callback(tls_context_, VerifyPinnedCertificate,
                                     &pin_);
  } else if (SSL_CTX_load_verify_locations(
                 tls_context_, config_.ca_certificate_path.c_str(), nullptr) !=
             1) {
    return OpenSslError("load server CA certificate failed");
  } else {
    X509_VERIFY_PARAM_set_flags(SSL_CTX_get0_param(tls_context_),
                                X509_V_FLAG_PARTIAL_CHAIN);
  }

  tls_ = SSL_new(tls_context_);
  if (tls_ == nullptr) {
    return OpenSslError("create TLS connection failed");
  }
  if (SSL_set_fd(tls_, static_cast<int>(socket_)) != 1) {
    return OpenSslError("attach TLS connection to socket failed");
  }
  if (!config_.server_name.empty() &&
      SSL_set_tlsext_host_name(tls_, config_.server_name.c_str()) != 1) {
    return OpenSslError("set TLS server name failed");
  }
  if (config_.spki_sha256_base64.empty() &&
      SSL_set1_host(tls_, config_.server_name.c_str()) != 1) {
    return OpenSslError("set TLS certificate hostname failed");
  }
  constexpr std::array<unsigned char, 9> kHttp11Alpn{
      {8U, 'h', 't', 't', 'p', '/', '1', '.', '1'}};
  if (SSL_set_alpn_protos(tls_, kHttp11Alpn.data(), kHttp11Alpn.size()) != 0) {
    return OpenSslError("set TLS ALPN failed");
  }
  return Status::Ok();
}

Status WssClient::Impl::ConnectTls(const Deadline deadline) {
#if !defined(_WIN32)
  ScopedSigpipeBlock sigpipe_block;
  if (!sigpipe_block.ready()) {
    return Status::Error(StatusCode::kInternal,
                         "block SIGPIPE for TLS handshake failed");
  }
#endif
  for (;;) {
    if (stop_requested_.load(std::memory_order_acquire)) {
      return CancelledStatus();
    }
    ERR_clear_error();
    const int result = SSL_connect(tls_);
    if (stop_requested_.load(std::memory_order_acquire)) {
      return CancelledStatus();
    }
    if (result == 1) {
      // Certificate-authenticated TLS completes only after the peer proves it
      // owns the private key corresponding to the accepted certificate SPKI.
      break;
    }
    const int error = SSL_get_error(tls_, result);
    if (error != SSL_ERROR_WANT_READ && error != SSL_ERROR_WANT_WRITE) {
      return OpenSslError("TLS handshake failed");
    }
    const auto wait_status =
        WaitForSocket(socket_, error == SSL_ERROR_WANT_READ, deadline,
                      stop_requested_);
    if (!wait_status.ok()) {
      return wait_status;
    }
  }
#if OPENSSL_VERSION_NUMBER >= 0x30000000L
  X509* const peer = SSL_get1_peer_certificate(tls_);
#else
  X509* const peer = SSL_get_peer_certificate(tls_);
#endif
  if (peer == nullptr) {
    return Status::Error(StatusCode::kFailedPrecondition,
                         "TLS server did not present a certificate");
  }
  X509_free(peer);
  if (SSL_get_verify_result(tls_) != X509_V_OK) {
    return Status::Error(StatusCode::kFailedPrecondition,
                         "TLS server certificate verification failed");
  }
  return Status::Ok();
}

Status WssClient::Impl::UpgradeWebSocket(const Deadline deadline) {
  std::array<std::uint8_t, 16> nonce{};
  if (RAND_bytes(nonce.data(), nonce.size()) != 1) {
    return OpenSslError("generate WebSocket handshake nonce failed");
  }
  const std::string key = Base64Encode(nonce.data(), nonce.size());
  if (key.empty()) {
    return Status::Error(StatusCode::kInternal,
                         "encode WebSocket handshake nonce failed");
  }
  const bool is_ipv6 = config_.server_ip.find(':') != std::string::npos;
  const std::string authority_host =
      !config_.server_name.empty()
          ? config_.server_name
          : (is_ipv6 ? "[" + config_.server_ip + "]" : config_.server_ip);
  const std::string host =
      authority_host + ":" + std::to_string(config_.server_port);
  const std::string request =
      std::string("GET ") + kWebSocketPath + " HTTP/1.1\r\nHost: " + host +
      "\r\nUpgrade: websocket\r\nConnection: Upgrade\r\n" +
      "Sec-WebSocket-Key: " + key +
      "\r\nSec-WebSocket-Version: 13\r\n\r\n";
  auto status = WriteTls(reinterpret_cast<const std::uint8_t*>(request.data()),
                         request.size(), deadline);
  if (!status.ok()) {
    return status;
  }

  std::string response;
  response.reserve(512U);
  while (response.size() < kMaximumHandshakeBytes &&
         (response.size() < 4U ||
          response.compare(response.size() - 4U, 4U, "\r\n\r\n") != 0)) {
    std::uint8_t byte = 0U;
    status = ReadTls(&byte, 1U, deadline);
    if (!status.ok()) {
      return status;
    }
    response.push_back(static_cast<char>(byte));
  }
  if (response.size() >= kMaximumHandshakeBytes ||
      response.compare(response.size() - 4U, 4U, "\r\n\r\n") != 0) {
    return Status::Error(StatusCode::kResourceExhausted,
                         "WebSocket handshake response is too large");
  }

  std::istringstream stream(response);
  std::string line;
  if (!std::getline(stream, line)) {
    return Status::Error(StatusCode::kFailedPrecondition,
                         "server rejected WebSocket upgrade");
  }
  if (!line.empty() && line.back() == '\r') {
    line.pop_back();
  }
  std::istringstream status_line(line);
  std::string http_version;
  unsigned int http_status = 0U;
  if (!(status_line >> http_version >> http_status) ||
      (http_version != "HTTP/1.1" && http_version != "HTTP/1.0") ||
      http_status != 101U) {
    return Status::Error(StatusCode::kFailedPrecondition,
                         "server rejected WebSocket upgrade");
  }
  std::string upgrade;
  std::string connection;
  std::string accept;
  while (std::getline(stream, line) && line != "\r") {
    if (!line.empty() && line.back() == '\r') {
      line.pop_back();
    }
    const auto separator = line.find(':');
    if (separator == std::string::npos) {
      return Status::Error(StatusCode::kInvalidArgument,
                           "malformed WebSocket handshake header");
    }
    const auto name = LowerAscii(TrimAscii(line.substr(0U, separator)));
    const auto value = TrimAscii(line.substr(separator + 1U));
    if (name == "upgrade") {
      upgrade = value;
    } else if (name == "connection") {
      connection = value;
    } else if (name == "sec-websocket-accept") {
      accept = value;
    }
  }
  std::string expected_accept;
  status = ExpectedWebSocketAccept(key, &expected_accept);
  if (!status.ok()) {
    return status;
  }
  if (LowerAscii(upgrade) != "websocket" ||
      !HeaderContainsToken(connection, "upgrade") ||
      accept != expected_accept) {
    return Status::Error(StatusCode::kFailedPrecondition,
                         "WebSocket upgrade response verification failed");
  }
  return Status::Ok();
}

Status WssClient::Impl::WriteTls(const std::uint8_t* data,
                                 const std::size_t data_size,
                                 const Deadline deadline) {
#if !defined(_WIN32)
  ScopedSigpipeBlock sigpipe_block;
  if (!sigpipe_block.ready()) {
    return Status::Error(StatusCode::kInternal,
                         "block SIGPIPE for TLS write failed");
  }
#endif
  std::size_t offset = 0U;
  while (offset < data_size) {
    if (stop_requested_.load(std::memory_order_acquire)) {
      return CancelledStatus();
    }
    const auto remaining = std::min<std::size_t>(
        data_size - offset, static_cast<std::size_t>(std::numeric_limits<int>::max()));
    ERR_clear_error();
    const int result =
        SSL_write(tls_, data + offset, static_cast<int>(remaining));
    if (stop_requested_.load(std::memory_order_acquire)) {
      return CancelledStatus();
    }
    if (result > 0) {
      offset += static_cast<std::size_t>(result);
      continue;
    }
    const int error = SSL_get_error(tls_, result);
    if (error != SSL_ERROR_WANT_READ && error != SSL_ERROR_WANT_WRITE) {
      return OpenSslError("write TLS stream failed");
    }
    const auto wait_status =
        WaitForSocket(socket_, error == SSL_ERROR_WANT_READ, deadline,
                      stop_requested_);
    if (!wait_status.ok()) {
      return wait_status;
    }
  }
  return Status::Ok();
}

Status WssClient::Impl::ReadTls(std::uint8_t* data,
                                const std::size_t data_size,
                                const Deadline deadline) {
#if !defined(_WIN32)
  ScopedSigpipeBlock sigpipe_block;
  if (!sigpipe_block.ready()) {
    return Status::Error(StatusCode::kInternal,
                         "block SIGPIPE for TLS read failed");
  }
#endif
  std::size_t offset = 0U;
  while (offset < data_size) {
    if (stop_requested_.load(std::memory_order_acquire)) {
      return CancelledStatus();
    }
    const auto remaining = std::min<std::size_t>(
        data_size - offset, static_cast<std::size_t>(std::numeric_limits<int>::max()));
    ERR_clear_error();
    const int result = SSL_read(tls_, data + offset, static_cast<int>(remaining));
    if (stop_requested_.load(std::memory_order_acquire)) {
      return CancelledStatus();
    }
    if (result > 0) {
      offset += static_cast<std::size_t>(result);
      continue;
    }
    const int error = SSL_get_error(tls_, result);
    if (error == SSL_ERROR_ZERO_RETURN) {
      return Status::Error(StatusCode::kFailedPrecondition,
                           "TLS peer closed the connection");
    }
    if (error != SSL_ERROR_WANT_READ && error != SSL_ERROR_WANT_WRITE) {
      return OpenSslError("read TLS stream failed");
    }
    const auto wait_status =
        WaitForSocket(socket_, error == SSL_ERROR_WANT_READ, deadline,
                      stop_requested_);
    if (!wait_status.ok()) {
      return wait_status;
    }
  }
  return Status::Ok();
}

Status WssClient::Impl::SendFrame(const std::uint8_t opcode,
                                  const std::uint8_t* const payload,
                                  const std::size_t payload_size,
                                  const Deadline deadline) {
  if (payload_size > 0U && payload == nullptr) {
    return Status::Error(StatusCode::kInvalidArgument,
                         "WebSocket payload must not be null");
  }
  if (payload_size > kMaximumWireMessageBytes) {
    return Status::Error(StatusCode::kResourceExhausted,
                         "WebSocket payload exceeds protocol bound");
  }
  if (opcode >= kOpcodeClose && payload_size > 125U) {
    return Status::Error(StatusCode::kInvalidArgument,
                         "WebSocket control payload exceeds 125 bytes");
  }

  std::vector<std::uint8_t> frame;
  const std::size_t length_bytes =
      payload_size < 126U ? 0U : (payload_size <= 0xFFFFU ? 2U : 8U);
  frame.resize(2U + length_bytes + 4U + payload_size);
  frame[0] = static_cast<std::uint8_t>(0x80U | opcode);
  std::size_t cursor = 2U;
  if (length_bytes == 0U) {
    frame[1] = static_cast<std::uint8_t>(0x80U | payload_size);
  } else if (length_bytes == 2U) {
    frame[1] = 0x80U | 126U;
    frame[cursor++] = static_cast<std::uint8_t>((payload_size >> 8U) & 0xFFU);
    frame[cursor++] = static_cast<std::uint8_t>(payload_size & 0xFFU);
  } else {
    frame[1] = 0x80U | 127U;
    const auto wire_size = static_cast<std::uint64_t>(payload_size);
    for (int shift = 56; shift >= 0; shift -= 8) {
      frame[cursor++] =
          static_cast<std::uint8_t>((wire_size >> shift) & 0xFFU);
    }
  }
  std::array<std::uint8_t, 4> mask{};
  if (RAND_bytes(mask.data(), mask.size()) != 1) {
    return OpenSslError("generate WebSocket frame mask failed");
  }
  std::copy(mask.begin(), mask.end(), frame.begin() + cursor);
  cursor += mask.size();
  for (std::size_t index = 0U; index < payload_size; ++index) {
    frame[cursor + index] = payload[index] ^ mask[index % mask.size()];
  }
  return WriteTls(frame.data(), frame.size(), deadline);
}

Status WssClient::Impl::ReadFrame(WebSocketFrame* const output,
                                  const Deadline deadline) {
  if (output == nullptr) {
    return Status::Error(StatusCode::kInvalidArgument,
                         "WebSocket frame output must not be null");
  }
  std::array<std::uint8_t, 2> header{};
  auto status = ReadTls(header.data(), header.size(), deadline);
  if (!status.ok()) {
    return status;
  }
  if ((header[0] & 0x70U) != 0U) {
    return Status::Error(StatusCode::kNotSupported,
                         "WebSocket extensions are not negotiated");
  }
  if ((header[1] & 0x80U) != 0U) {
    return Status::Error(StatusCode::kInvalidArgument,
                         "server WebSocket frames must not be masked");
  }
  const bool final = (header[0] & 0x80U) != 0U;
  const std::uint8_t opcode = header[0] & 0x0FU;
  std::uint64_t payload_size = header[1] & 0x7FU;
  if (payload_size == 126U) {
    std::array<std::uint8_t, 2> length{};
    status = ReadTls(length.data(), length.size(), deadline);
    if (!status.ok()) {
      return status;
    }
    payload_size = (static_cast<std::uint64_t>(length[0]) << 8U) | length[1];
  } else if (payload_size == 127U) {
    std::array<std::uint8_t, 8> length{};
    status = ReadTls(length.data(), length.size(), deadline);
    if (!status.ok()) {
      return status;
    }
    if ((length[0] & 0x80U) != 0U) {
      return Status::Error(StatusCode::kInvalidArgument,
                           "WebSocket payload length has the reserved high bit");
    }
    payload_size = 0U;
    for (const std::uint8_t byte : length) {
      payload_size = (payload_size << 8U) | byte;
    }
  }
  const bool is_control = opcode >= kOpcodeClose;
  if ((is_control && (!final || payload_size > 125U)) ||
      payload_size > kMaximumWireMessageBytes) {
    return Status::Error(StatusCode::kResourceExhausted,
                         "WebSocket frame violates protocol bounds");
  }
  WebSocketFrame frame{};
  frame.final = final;
  frame.opcode = opcode;
  frame.payload.resize(static_cast<std::size_t>(payload_size));
  status = ReadTls(frame.payload.data(), frame.payload.size(), deadline);
  if (!status.ok()) {
    return status;
  }
  *output = std::move(frame);
  return Status::Ok();
}

Status WssClient::Impl::ReadDataMessage(
    std::uint8_t* const opcode,
    std::vector<std::uint8_t>* const payload) {
  if (opcode == nullptr || payload == nullptr) {
    return Status::Error(StatusCode::kInvalidArgument,
                         "WebSocket message output must not be null");
  }
  bool fragmented = false;
  payload->clear();
  auto idle_deadline =
      std::chrono::steady_clock::now() +
      std::chrono::milliseconds(config_.receive_idle_timeout_ms);
  for (;;) {
    WebSocketFrame frame{};
    auto status = ReadFrame(&frame, idle_deadline);
    if (!status.ok()) {
      return status;
    }
    idle_deadline = std::chrono::steady_clock::now() +
                    std::chrono::milliseconds(
                        config_.receive_idle_timeout_ms);
    if (frame.opcode == kOpcodePing) {
      const auto write_deadline =
          std::chrono::steady_clock::now() +
          std::chrono::milliseconds(config_.write_timeout_ms);
      status = SendFrame(kOpcodePong, frame.payload.data(),
                         frame.payload.size(), write_deadline);
      if (!status.ok()) {
        return status;
      }
      idle_deadline = std::chrono::steady_clock::now() +
                      std::chrono::milliseconds(
                          config_.receive_idle_timeout_ms);
      continue;
    }
    if (frame.opcode == kOpcodePong) {
      continue;
    }
    if (frame.opcode == kOpcodeClose) {
      return Status::Error(StatusCode::kFailedPrecondition,
                           "WebSocket peer closed the connection");
    }
    if (frame.opcode == kOpcodeContinuation) {
      if (!fragmented) {
        return Status::Error(StatusCode::kInvalidArgument,
                             "unexpected WebSocket continuation frame");
      }
    } else if (frame.opcode == kOpcodeText || frame.opcode == kOpcodeBinary) {
      if (fragmented) {
        return Status::Error(StatusCode::kInvalidArgument,
                             "new WebSocket message interrupted fragments");
      }
      *opcode = frame.opcode;
      fragmented = !frame.final;
    } else {
      return Status::Error(StatusCode::kNotSupported,
                           "unsupported WebSocket frame opcode");
    }
    if (frame.payload.size() > kMaximumWireMessageBytes - payload->size()) {
      return Status::Error(StatusCode::kResourceExhausted,
                           "fragmented WebSocket message exceeds protocol bound");
    }
    payload->insert(payload->end(), frame.payload.begin(), frame.payload.end());
    if (frame.final) {
      return Status::Ok();
    }
  }
}

Status WssClient::Impl::SendControl(const std::string& control_json) {
  if (!connected_) {
    return Status::Error(StatusCode::kFailedPrecondition,
                         "WSS client is not connected");
  }
  if (control_json.empty() ||
      control_json.size() > protocol::kMaximumControlFrameBytes) {
    return Status::Error(StatusCode::kInvalidArgument,
                         "control frame size is outside protocol bounds");
  }
  const std::vector<std::uint8_t> bytes(control_json.begin(),
                                        control_json.end());
  if (!IsValidUtf8(bytes)) {
    return Status::Error(StatusCode::kInvalidArgument,
                         "control frame is not valid UTF-8");
  }
  const auto deadline = std::chrono::steady_clock::now() +
                        std::chrono::milliseconds(config_.write_timeout_ms);
  return SendFrame(kOpcodeText,
                   reinterpret_cast<const std::uint8_t*>(control_json.data()),
                   control_json.size(), deadline);
}

Status WssClient::Impl::SendPcm(
    const protocol::AudioPacketHeader& header,
    const std::uint8_t* const payload,
    const std::size_t payload_size_bytes) {
  if (!connected_) {
    return Status::Error(StatusCode::kFailedPrecondition,
                         "WSS client is not connected");
  }
  if (header.kind != protocol::AudioPacketKind::kUplink ||
      header.sample_rate_hz != 16000U ||
      payload_size_bytes != header.payload_length_bytes ||
      (payload_size_bytes > 0U && payload == nullptr)) {
    return Status::Error(StatusCode::kInvalidArgument,
                         "uplink PCM must be matching 16 kHz protocol audio");
  }
  std::array<std::uint8_t, protocol::kAudioPacketHeaderSize> encoded_header{};
  auto status = protocol::EncodeAudioPacketHeader(header, &encoded_header);
  if (!status.ok()) {
    return status;
  }
  std::vector<std::uint8_t> frame(encoded_header.begin(), encoded_header.end());
  frame.insert(frame.end(), payload, payload + payload_size_bytes);
  const auto deadline = std::chrono::steady_clock::now() +
                        std::chrono::milliseconds(config_.write_timeout_ms);
  return SendFrame(kOpcodeBinary, frame.data(), frame.size(), deadline);
}

Status WssClient::Impl::SendKeepAlivePong() {
  if (!connected_) {
    return Status::Error(StatusCode::kFailedPrecondition,
                         "WSS client is not connected");
  }
  const auto deadline = std::chrono::steady_clock::now() +
                        std::chrono::milliseconds(config_.write_timeout_ms);
  return SendFrame(kOpcodePong, nullptr, 0U, deadline);
}

Status WssClient::Impl::Receive(WssInboundMessage* const output) {
  if (output == nullptr) {
    return Status::Error(StatusCode::kInvalidArgument,
                         "WSS receive output must not be null");
  }
  if (!connected_) {
    return Status::Error(StatusCode::kFailedPrecondition,
                         "WSS client is not connected");
  }
  std::uint8_t opcode = 0U;
  std::vector<std::uint8_t> payload;
  auto status = ReadDataMessage(&opcode, &payload);
  if (!status.ok()) {
    return status;
  }

  WssInboundMessage message{};
  if (opcode == kOpcodeText) {
    if (payload.empty() ||
        payload.size() > protocol::kMaximumControlFrameBytes ||
        !IsValidUtf8(payload)) {
      return Status::Error(StatusCode::kInvalidArgument,
                           "received control frame is invalid UTF-8 or size");
    }
    message.type = WssInboundMessageType::kControl;
    message.control_json.assign(payload.begin(), payload.end());
  } else {
    protocol::AudioPacketHeader header{};
    status = protocol::DecodeAudioPacketHeader(payload.data(), payload.size(),
                                               &header);
    if (!status.ok()) {
      return status;
    }
    if (header.kind != protocol::AudioPacketKind::kDownlink ||
        header.sample_rate_hz != 24000U) {
      return Status::Error(StatusCode::kFailedPrecondition,
                           "downlink PCM must be protocol v1 24 kHz mono");
    }
    message.type = WssInboundMessageType::kPcm24k;
    message.pcm_header = header;
    message.pcm_payload.assign(
        payload.begin() +
            static_cast<std::ptrdiff_t>(protocol::kAudioPacketHeaderSize),
        payload.end());
  }
  *output = std::move(message);
  return Status::Ok();
}

void WssClient::Impl::RequestStop() noexcept {
  stop_requested_.store(true, std::memory_order_release);
  std::lock_guard<std::mutex> lock(socket_lifetime_mutex_);
  ShutdownSocket(socket_);
}

void WssClient::Impl::Close() noexcept {
  if (connected_ && tls_ != nullptr &&
      !stop_requested_.load(std::memory_order_acquire)) {
    const auto deadline = std::chrono::steady_clock::now() +
                          std::chrono::milliseconds(250U);
    const std::array<std::uint8_t, 2> normal_close{{0x03U, 0xE8U}};
    (void)SendFrame(kOpcodeClose, normal_close.data(), normal_close.size(),
                    deadline);
#if defined(_WIN32)
    (void)SSL_shutdown(tls_);
#else
    ScopedSigpipeBlock sigpipe_block;
    if (sigpipe_block.ready()) {
      (void)SSL_shutdown(tls_);
    }
#endif
  }
  Reset();
}

void WssClient::Impl::Reset() noexcept {
  connected_ = false;
  if (tls_ != nullptr) {
    SSL_free(tls_);
    tls_ = nullptr;
  }
  if (tls_context_ != nullptr) {
    SSL_CTX_free(tls_context_);
    tls_context_ = nullptr;
  }
  NativeSocket socket_to_close = kInvalidSocket;
  {
    std::lock_guard<std::mutex> lock(socket_lifetime_mutex_);
    socket_to_close = socket_;
    socket_ = kInvalidSocket;
  }
  CloseSocket(socket_to_close);
}

