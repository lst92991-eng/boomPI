Status CancelledStatus() {
  return Status::Error(StatusCode::kFailedPrecondition,
                       "network operation cancelled");
}

#if !defined(_WIN32)
// OpenSSL's socket BIO can write during handshakes, reads, writes and shutdown.
// Blocking SIGPIPE only on the network-owner thread avoids a process-wide
// signal-policy change. A signal generated by this scope is consumed before
// restoring the caller's signal mask.
class ScopedSigpipeBlock final {
 public:
  ScopedSigpipeBlock() noexcept {
    if (sigemptyset(&sigpipe_set_) != 0 ||
        sigaddset(&sigpipe_set_, SIGPIPE) != 0) {
      return;
    }
    if (pthread_sigmask(SIG_BLOCK, &sigpipe_set_, &previous_mask_) != 0) {
      return;
    }
    mask_changed_ = true;
    const int previously_blocked = sigismember(&previous_mask_, SIGPIPE);
    if (previously_blocked < 0) {
      RestoreMask();
      return;
    }
    if (previously_blocked != 0) {
      ready_ = true;
      return;
    }
    owns_block_ = true;
    sigset_t pending{};
    if (sigpending(&pending) != 0) {
      RestoreMask();
      return;
    }
    const int previously_pending = sigismember(&pending, SIGPIPE);
    if (previously_pending < 0) {
      RestoreMask();
      return;
    }
    had_pending_sigpipe_ = previously_pending != 0;
    ready_ = true;
  }

  ~ScopedSigpipeBlock() {
    if (!mask_changed_) {
      return;
    }
    if (ready_ && owns_block_ && !had_pending_sigpipe_) {
      sigset_t pending{};
      if (sigpending(&pending) == 0 &&
          sigismember(&pending, SIGPIPE) == 1) {
        timespec no_wait{};
        while (sigtimedwait(&sigpipe_set_, nullptr, &no_wait) < 0 &&
               errno == EINTR) {
        }
      }
    }
    RestoreMask();
  }

  ScopedSigpipeBlock(const ScopedSigpipeBlock&) = delete;
  ScopedSigpipeBlock& operator=(const ScopedSigpipeBlock&) = delete;

  bool ready() const noexcept { return ready_; }

 private:
  void RestoreMask() noexcept {
    if (mask_changed_) {
      (void)pthread_sigmask(SIG_SETMASK, &previous_mask_, nullptr);
      mask_changed_ = false;
    }
  }

  sigset_t sigpipe_set_{};
  sigset_t previous_mask_{};
  bool mask_changed_{false};
  bool owns_block_{false};
  bool had_pending_sigpipe_{false};
  bool ready_{false};
};
#endif

Status OpenSslError(const char* const operation) {
  const unsigned long code = ERR_get_error();
  if (code == 0U) {
    return Status::Error(StatusCode::kInternal, operation);
  }
  std::array<char, 256> buffer{};
  ERR_error_string_n(code, buffer.data(), buffer.size());
  return Status::Error(StatusCode::kInternal,
                       std::string(operation) + ": " + buffer.data());
}

void CloseSocket(const NativeSocket socket) noexcept {
  if (socket == kInvalidSocket) {
    return;
  }
#if defined(_WIN32)
  closesocket(socket);
#else
  close(socket);
#endif
}

void ShutdownSocket(const NativeSocket socket) noexcept {
  if (socket == kInvalidSocket) {
    return;
  }
#if defined(_WIN32)
  (void)shutdown(socket, SD_BOTH);
#else
  (void)shutdown(socket, SHUT_RDWR);
#endif
}

Status InitializeSocketApi() {
#if defined(_WIN32)
  static const int result = []() {
    WSADATA data{};
    return WSAStartup(MAKEWORD(2, 2), &data);
  }();
  if (result != 0) {
    return Status::Error(StatusCode::kInternal,
                         "initialize Windows socket API failed");
  }
#endif
  return Status::Ok();
}

Status SetNonBlocking(const NativeSocket socket) {
#if defined(_WIN32)
  u_long enabled = 1U;
  if (ioctlsocket(socket, FIONBIO, &enabled) != 0) {
    return Status::Error(StatusCode::kInternal,
                         "set socket nonblocking mode failed");
  }
#else
  const int flags = fcntl(socket, F_GETFL, 0);
  if (flags < 0 || fcntl(socket, F_SETFL, flags | O_NONBLOCK) != 0) {
    return Status::Error(StatusCode::kInternal,
                         "set socket nonblocking mode failed");
  }
#endif
  return Status::Ok();
}

bool ConnectIsInProgress() {
#if defined(_WIN32)
  const int error = WSAGetLastError();
  return error == WSAEWOULDBLOCK || error == WSAEINPROGRESS ||
         error == WSAEINVAL;
#else
  return errno == EINPROGRESS;
#endif
}

Status WaitForSocket(const NativeSocket socket,
                     const bool wait_for_read,
                     const Deadline deadline,
                     const std::atomic<bool>& stop_requested) {
  for (;;) {
    if (stop_requested.load(std::memory_order_acquire)) {
      return CancelledStatus();
    }
    const auto now = std::chrono::steady_clock::now();
    if (now >= deadline) {
      return Status::Error(StatusCode::kResourceExhausted,
                           "network operation timed out");
    }
    const auto remaining_us =
        std::chrono::duration_cast<std::chrono::microseconds>(deadline - now);
#if defined(_WIN32)
    timeval timeout{};
    timeout.tv_sec = static_cast<long>(remaining_us.count() / 1000000);
    timeout.tv_usec = static_cast<long>(remaining_us.count() % 1000000);

    fd_set read_set;
    fd_set write_set;
    FD_ZERO(&read_set);
    FD_ZERO(&write_set);
    if (wait_for_read) {
      FD_SET(socket, &read_set);
    } else {
      FD_SET(socket, &write_set);
    }
    const int result = select(0, wait_for_read ? &read_set : nullptr,
                              wait_for_read ? nullptr : &write_set, nullptr,
                              &timeout);
#else
    pollfd descriptor{};
    descriptor.fd = socket;
    descriptor.events = wait_for_read ? POLLIN : POLLOUT;
    const auto timeout_ms =
        static_cast<int>((remaining_us.count() + 999) / 1000);
    const int result = poll(&descriptor, 1U, timeout_ms);
#endif
    if (stop_requested.load(std::memory_order_acquire)) {
      return CancelledStatus();
    }
    if (result > 0) {
#if !defined(_WIN32)
      if ((descriptor.revents & POLLNVAL) != 0) {
        return Status::Error(StatusCode::kInternal,
                             "network socket is invalid");
      }
#endif
      return Status::Ok();
    }
    if (result == 0) {
      return Status::Error(StatusCode::kResourceExhausted,
                           "network operation timed out");
    }
#if !defined(_WIN32)
    if (errno == EINTR) {
      continue;
    }
#endif
    return Status::Error(StatusCode::kInternal,
                         "wait for network socket failed");
  }
}

Status DecodeSha256Pin(const std::string& encoded,
                       std::array<std::uint8_t, kSha256Bytes>* const output) {
  if (output == nullptr || encoded.size() != 44U || encoded[43] != '=') {
    return Status::Error(StatusCode::kInvalidArgument,
                         "SPKI SHA-256 pin must be 44-byte base64");
  }
  std::array<unsigned char, 33> decoded{};
  const int decoded_size =
      EVP_DecodeBlock(decoded.data(),
                      reinterpret_cast<const unsigned char*>(encoded.data()),
                      static_cast<int>(encoded.size()));
  const std::size_t padding = encoded[42] == '=' ? 2U : 1U;
  if (decoded_size < 0 ||
      static_cast<std::size_t>(decoded_size) - padding != output->size()) {
    return Status::Error(StatusCode::kInvalidArgument,
                         "SPKI SHA-256 pin is not valid base64");
  }
  std::copy_n(decoded.begin(), output->size(), output->begin());
  return Status::Ok();
}

int VerifyPinnedCertificate(X509_STORE_CTX* const store, void* const argument) {
  // A stable SPKI is the identity in pin mode, so wall-clock validity is
  // deliberately out of scope. TLS still proves possession of the matching
  // private key, while this callback enforces server purpose and the pin.
  const auto* const pin = static_cast<const PinContext*>(argument);
  X509* const certificate = X509_STORE_CTX_get0_cert(store);
  if (pin == nullptr || certificate == nullptr ||
      X509_check_purpose(certificate, X509_PURPOSE_SSL_SERVER, 0) <= 0) {
    X509_STORE_CTX_set_error(store, X509_V_ERR_CERT_REJECTED);
    return 0;
  }

  X509_PUBKEY* const public_key = X509_get_X509_PUBKEY(certificate);
  const int encoded_size = i2d_X509_PUBKEY(public_key, nullptr);
  if (encoded_size <= 0) {
    X509_STORE_CTX_set_error(store, X509_V_ERR_UNSPECIFIED);
    return 0;
  }
  std::array<unsigned char, 4096> encoded{};
  if (static_cast<std::size_t>(encoded_size) > encoded.size()) {
    X509_STORE_CTX_set_error(store, X509_V_ERR_UNSPECIFIED);
    return 0;
  }
  unsigned char* cursor = encoded.data();
  if (i2d_X509_PUBKEY(public_key, &cursor) != encoded_size) {
    X509_STORE_CTX_set_error(store, X509_V_ERR_UNSPECIFIED);
    return 0;
  }
  std::array<unsigned char, EVP_MAX_MD_SIZE> digest{};
  unsigned int digest_size = 0U;
  if (EVP_Digest(encoded.data(), static_cast<std::size_t>(encoded_size),
                 digest.data(), &digest_size, EVP_sha256(), nullptr) != 1 ||
      digest_size != pin->digest.size() ||
      CRYPTO_memcmp(digest.data(), pin->digest.data(), pin->digest.size()) !=
          0) {
    X509_STORE_CTX_set_error(store, X509_V_ERR_CERT_REJECTED);
    return 0;
  }
  X509_STORE_CTX_set_error(store, X509_V_OK);
  return 1;
}

std::string LowerAscii(std::string value) {
  std::transform(value.begin(), value.end(), value.begin(), [](const char ch) {
    return ch >= 'A' && ch <= 'Z' ? static_cast<char>(ch + ('a' - 'A')) : ch;
  });
  return value;
}

bool IsSafeServerName(const std::string& server_name) {
  if (server_name.empty() || server_name.size() > 253U) {
    return false;
  }
  return std::all_of(server_name.begin(), server_name.end(), [](const char ch) {
    const auto value = static_cast<unsigned char>(ch);
    return (value >= static_cast<unsigned char>('a') &&
            value <= static_cast<unsigned char>('z')) ||
           (value >= static_cast<unsigned char>('A') &&
            value <= static_cast<unsigned char>('Z')) ||
           (value >= static_cast<unsigned char>('0') &&
            value <= static_cast<unsigned char>('9')) ||
           ch == '-' || ch == '.' || ch == '_';
  });
}

std::string TrimAscii(const std::string& value) {
  const auto begin = value.find_first_not_of(" \t");
  if (begin == std::string::npos) {
    return {};
  }
  const auto end = value.find_last_not_of(" \t");
  return value.substr(begin, end - begin + 1U);
}

bool HeaderContainsToken(const std::string& value,
                         const std::string& expected_token) {
  std::size_t begin = 0U;
  while (begin <= value.size()) {
    const auto end = value.find(',', begin);
    const auto token = LowerAscii(TrimAscii(value.substr(
        begin, end == std::string::npos ? std::string::npos : end - begin)));
    if (token == expected_token) {
      return true;
    }
    if (end == std::string::npos) {
      break;
    }
    begin = end + 1U;
  }
  return false;
}

bool IsValidUtf8(const std::vector<std::uint8_t>& data) {
  std::size_t index = 0U;
  while (index < data.size()) {
    const std::uint8_t first = data[index++];
    if (first <= 0x7FU) {
      continue;
    }
    std::size_t continuation_count = 0U;
    std::uint32_t value = 0U;
    std::uint32_t minimum = 0U;
    if ((first & 0xE0U) == 0xC0U) {
      continuation_count = 1U;
      value = first & 0x1FU;
      minimum = 0x80U;
    } else if ((first & 0xF0U) == 0xE0U) {
      continuation_count = 2U;
      value = first & 0x0FU;
      minimum = 0x800U;
    } else if ((first & 0xF8U) == 0xF0U) {
      continuation_count = 3U;
      value = first & 0x07U;
      minimum = 0x10000U;
    } else {
      return false;
    }
    if (continuation_count > data.size() - index) {
      return false;
    }
    for (std::size_t count = 0U; count < continuation_count; ++count) {
      const std::uint8_t next = data[index++];
      if ((next & 0xC0U) != 0x80U) {
        return false;
      }
      value = (value << 6U) | (next & 0x3FU);
    }
    if (value < minimum || value > 0x10FFFFU ||
        (value >= 0xD800U && value <= 0xDFFFU)) {
      return false;
    }
  }
  return true;
}

std::string Base64Encode(const std::uint8_t* const data,
                         const std::size_t data_size) {
  std::string encoded(4U * ((data_size + 2U) / 3U), '\0');
  const int size = EVP_EncodeBlock(
      reinterpret_cast<unsigned char*>(encoded.data()), data,
      static_cast<int>(data_size));
  if (size <= 0) {
    return {};
  }
  encoded.resize(static_cast<std::size_t>(size));
  return encoded;
}

Status ExpectedWebSocketAccept(const std::string& key, std::string* output) {
  if (output == nullptr) {
    return Status::Error(StatusCode::kInvalidArgument,
                         "WebSocket accept output must not be null");
  }
  const std::string input = key + kWebSocketGuid;
  std::array<unsigned char, EVP_MAX_MD_SIZE> digest{};
  unsigned int digest_size = 0U;
  if (EVP_Digest(input.data(), input.size(), digest.data(), &digest_size,
                 EVP_sha1(), nullptr) != 1 ||
      digest_size != 20U) {
    return OpenSslError("compute WebSocket handshake digest failed");
  }
  *output = Base64Encode(digest.data(), digest_size);
  if (output->empty()) {
    return Status::Error(StatusCode::kInternal,
                         "encode WebSocket handshake digest failed");
  }
  return Status::Ok();
}

